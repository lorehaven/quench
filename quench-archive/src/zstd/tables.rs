/// The code a literal length falls in.
pub fn literal_length_code(length: u32) -> usize {
    LITERAL_LENGTH_CODES.partition_point(|&(base, _)| base <= length) - 1
}

/// The code a match length (3 or more) falls in.
pub fn match_length_code(length: u32) -> usize {
    MATCH_LENGTH_CODES.partition_point(|&(base, _)| base <= length) - 1
}
