/// What a source tarball leaves out: build output, version control, editor state and signing keys.
const SKIP_DIRS: &[&str] = &[
    "target",
    "dist",
    ".git",
    ".idea",
    ".gradle",
    "build",
    "node_modules",
];
const SKIP_FILES: &[&str] = &["local.properties", ".DS_Store"];
const SKIP_EXTENSIONS: &[&str] = &["keystore", "jks", "so"];

fn skipped(path: &Path, dir: bool) -> bool {
    let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
        return true;
    };
    if dir {
        return SKIP_DIRS.contains(&name);
    }
    SKIP_FILES.contains(&name)
        || path
            .extension()
            .and_then(|e| e.to_str())
            .is_some_and(|e| SKIP_EXTENSIONS.contains(&e))
}

fn collect(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)?.flatten().collect();
    entries.sort_by_key(std::fs::DirEntry::file_name);
    for entry in entries {
        let path = entry.path();
        let kind = entry.file_type()?;
        if kind.is_dir() {
            if !skipped(&path, true) {
                collect(&path, out)?;
            }
        } else if kind.is_file() && !skipped(&path, false) {
            out.push(path);
        }
    }
    Ok(())
}

/// The workspace manifest of a project that sits inside a larger workspace, cut down to the project's own members, so
/// the tarball builds on its own: `members = [...]` keeps only the crates under `prefix`.
fn trimmed_workspace(manifest: &str, prefix: &str) -> Result<String> {
    let Some(start) = manifest.find("members = [") else {
        return fail("the workspace Cargo.toml has no `members = [`");
    };
    let open = start + "members = [".len();
    let Some(close) = manifest[open..].find(']') else {
        return fail("the workspace Cargo.toml has an unterminated `members`");
    };
    let kept: Vec<String> = manifest[open..open + close]
        .split(',')
        .map(|m| m.trim().trim_matches('"').to_string())
        .filter(|m| m.starts_with(prefix))
        .map(|m| format!("  \"{m}\","))
        .collect();
    Ok(format!(
        "{}members = [\n{}\n]{}",
        &manifest[..start],
        kept.join("\n"),
        &manifest[open + close + 1..]
    ))
}

/// `quench build source`: `dist/<name>-<version>.tar.gz`, the project's sources to build from.
///
/// A project inside a larger workspace brings the workspace's `Cargo.toml` (cut down to its own crates) and
/// `Cargo.lock`, so `cargo build --release` works in the unpacked tree.
///
/// # Errors
/// A file that cannot be read or written, or a workspace manifest in a shape this does not know.
pub fn source(out: &mut dyn Write, project: &Project) -> Result<PathBuf> {
    let version = linux::version(project);
    let top = format!("{}-{version}", project.name);
    let workspace = project.workspace_root();
    let mut paths = Vec::new();
    collect(&project.root, &mut paths)?;

    let mut tar = quench_archive::tar::Builder::new();
    let mtime = build_time();
    let put = |tar: &mut quench_archive::tar::Builder, rel: &str, data: &[u8], exec: bool| {
        let mut header = quench_archive::tar::Header::file(&format!("{top}/{rel}"));
        header.mode = if exec { 0o755 } else { 0o644 };
        header.mtime = mtime;
        tar.append(&header, data).map_err(err)
    };
    // Paths are kept relative to the workspace, so the members still name them.
    let base = if project.flat() {
        &workspace
    } else {
        &project.root
    };
    if project.flat() {
        let prefix = project.member_path("");
        let manifest = std::fs::read_to_string(project.workspace_manifest())?;
        put(
            &mut tar,
            "Cargo.toml",
            trimmed_workspace(&manifest, &prefix)?.as_bytes(),
            false,
        )?;
        if let Ok(lock) = std::fs::read(workspace.join("Cargo.lock")) {
            put(&mut tar, "Cargo.lock", &lock, false)?;
        }
    }
    for path in &paths {
        let rel = path
            .strip_prefix(base)
            .map_err(err)?
            .to_string_lossy()
            .replace('\\', "/");
        let exec = {
            use std::os::unix::fs::PermissionsExt as _;
            std::fs::metadata(path)?.permissions().mode() & 0o111 != 0
        };
        put(&mut tar, &rel, &std::fs::read(path)?, exec)?;
    }
    std::fs::create_dir_all(project.dist())?;
    let target = project.dist().join(format!("{top}.tar.gz"));
    std::fs::write(&target, quench_archive::gzip::compress(&tar.finish()))?;
    writeln!(out, "source {} ({} files)", target.display(), paths.len())?;
    Ok(target)
}
