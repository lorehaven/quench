//! The packages of the Linux desktop build besides the `.deb`: an RPM, an Arch package and a source tarball.
//!
//! Each holds the same two files as the `.deb` (the release binary in `/usr/bin` and the menu entry) and is written
//! by hand from its format, so nothing but the standard library and the framework's own archive and hash crates is
//! used. `rpm -K`, `pacman -Qip` and `dpkg-deb` read what these produce.

// RPM and cpio store sizes, counts and times in 32 bits; a package this tool writes is far below that.
#![allow(clippy::cast_possible_truncation)]

use std::io::Write;
use std::path::{Path, PathBuf};

use crate::error::{Error, Result, fail};
use crate::linux;
use crate::project::Project;
use crate::system::System;

/// The release is `1` of the version: a repackaging of the same version would raise it.
const RELEASE: &str = "1";

/// Seconds since the epoch the packages are stamped with: `SOURCE_DATE_EPOCH` when set (a reproducible build),
/// else now.
fn build_time() -> u64 {
    std::env::var("SOURCE_DATE_EPOCH")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or_else(|| {
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map_or(0, |d| d.as_secs())
        })
}

/// What every package installs.
struct Files {
    name: String,
    version: String,
    summary: String,
    binary: Vec<u8>,
    desktop_path: String,
    desktop: String,
}

fn files(sys: &dyn System, out: &mut dyn Write, project: &Project) -> Result<Files> {
    let built = linux::build(sys, out, project, true)?;
    Ok(Files {
        name: project.name.clone(),
        version: linux::version(project),
        summary: linux::title(project),
        binary: std::fs::read(&built)?,
        desktop_path: format!("/usr/share/applications/{}.desktop", linux::app_id(project)),
        desktop: linux::desktop_entry(project),
    })
}

fn err<E: std::fmt::Display>(e: E) -> Error {
    Error(e.to_string())
}

// ------------------------------------------------------------------------------------------------ Arch

/// `quench build arch`: `dist/<name>-<version>-1-x86_64.pkg.tar.zst`, which `pacman -U` installs.
///
/// # Errors
/// As [`linux::build`], or a file that cannot be written.
pub fn arch(sys: &dyn System, out: &mut dyn Write, project: &Project) -> Result<PathBuf> {
    let f = files(sys, out, project)?;
    let size = f.binary.len() + f.desktop.len();
    let info = format!(
        "# Generated by quench\npkgname = {name}\npkgbase = {name}\npkgver = {version}-{RELEASE}\npkgdesc = {summary}\nbuilddate = {time}\npackager = Unknown Packager\nsize = {size}\narch = x86_64\n",
        name = f.name,
        version = f.version,
        summary = f.summary,
        time = build_time(),
    );
    let mut tar = quench_archive::tar::Builder::new();
    let mut header = quench_archive::tar::Header::file(".PKGINFO");
    header.mtime = build_time();
    tar.append(&header, info.as_bytes()).map_err(err)?;
    let mut exe = quench_archive::tar::Header::file(&format!("usr/bin/{}", f.name));
    exe.mode = 0o755;
    exe.mtime = build_time();
    tar.append(&exe, &f.binary).map_err(err)?;
    let mut entry = quench_archive::tar::Header::file(f.desktop_path.trim_start_matches('/'));
    entry.mtime = build_time();
    tar.append(&entry, f.desktop.as_bytes()).map_err(err)?;
    let target = project.dist().join(format!(
        "{}-{}-{RELEASE}-x86_64.pkg.tar.zst",
        f.name, f.version
    ));
    std::fs::write(&target, quench_archive::zstd::compress(&tar.finish()))?;
    writeln!(out, "arch {}", target.display())?;
    Ok(target)
}

// ------------------------------------------------------------------------------------------------- RPM

// Header entry types.
const INT16: u32 = 3;
const INT32: u32 = 4;
const STRING: u32 = 6;
const STRING_ARRAY: u32 = 8;

/// One header of an RPM: tags with their values, written sorted, as the format wants.
#[derive(Default)]
struct RpmHeader {
    entries: Vec<(u32, u32, u32, Vec<u8>)>,
}

impl RpmHeader {
    fn int16(&mut self, tag: u32, values: &[u16]) {
        let data = values.iter().flat_map(|v| v.to_be_bytes()).collect();
        self.entries.push((tag, INT16, values.len() as u32, data));
    }

    fn int32(&mut self, tag: u32, values: &[u32]) {
        let data = values.iter().flat_map(|v| v.to_be_bytes()).collect();
        self.entries.push((tag, INT32, values.len() as u32, data));
    }

    fn string(&mut self, tag: u32, value: &str) {
        let mut data = value.as_bytes().to_vec();
        data.push(0);
        self.entries.push((tag, STRING, 1, data));
    }

    fn strings(&mut self, tag: u32, values: &[&str]) {
        let mut data = Vec::new();
        for v in values {
            data.extend_from_slice(v.as_bytes());
            data.push(0);
        }
        self.entries
            .push((tag, STRING_ARRAY, values.len() as u32, data));
    }

    /// The header as bytes: magic, counts, the index, then the data, each value aligned for its type.
    ///
    /// `region` is the tag that marks the header as one unit (`62` for the signature header, `63` for the other): an
    /// entry first in the index whose data, last in the store, says how many entries it covers. A header without
    /// one is the old, version 3 shape, which `rpm` warns about.
    fn encode(mut self, region: u32) -> Vec<u8> {
        self.entries.sort_by_key(|e| e.0);
        let count = self.entries.len() as u32 + 1;
        let mut index = Vec::new();
        let mut data: Vec<u8> = Vec::new();
        for (tag, kind, n, bytes) in &self.entries {
            let align = match *kind {
                INT16 => 2,
                INT32 => 4,
                _ => 1,
            };
            while !data.len().is_multiple_of(align) {
                data.push(0);
            }
            index.extend_from_slice(&tag.to_be_bytes());
            index.extend_from_slice(&kind.to_be_bytes());
            index.extend_from_slice(&(data.len() as u32).to_be_bytes());
            index.extend_from_slice(&n.to_be_bytes());
            data.extend_from_slice(bytes);
        }
        let mut region_entry = Vec::new();
        region_entry.extend_from_slice(&region.to_be_bytes());
        region_entry.extend_from_slice(&7u32.to_be_bytes());
        region_entry.extend_from_slice(&(data.len() as u32).to_be_bytes());
        region_entry.extend_from_slice(&16u32.to_be_bytes());
        let trailer_offset = (-(count * 16).cast_signed()).to_be_bytes();
        data.extend_from_slice(&region.to_be_bytes());
        data.extend_from_slice(&7u32.to_be_bytes());
        data.extend_from_slice(&trailer_offset);
        data.extend_from_slice(&16u32.to_be_bytes());
        let mut out = vec![0x8e, 0xad, 0xe8, 0x01, 0, 0, 0, 0];
        out.extend_from_slice(&count.to_be_bytes());
        out.extend_from_slice(&(data.len() as u32).to_be_bytes());
        out.extend(region_entry);
        out.extend(index);
        out.extend(data);
        out
    }
}

/// A cpio archive in the "newc" format, which an RPM's payload is.
fn cpio(files: &[(&str, u32, &[u8])], time: u64) -> Vec<u8> {
    let mut out = Vec::new();
    let mut entry = |ino: u32, name: &str, mode: u32, data: &[u8]| {
        let name_size = name.len() + 1;
        let fields = [
            ino,
            mode,
            0,
            0,
            1,
            time as u32,
            data.len() as u32,
            0,
            0,
            0,
            0,
            name_size as u32,
            0,
        ];
        out.extend_from_slice(b"070701");
        for f in fields {
            out.extend_from_slice(format!("{f:08X}").as_bytes());
        }
        out.extend_from_slice(name.as_bytes());
        out.push(0);
        while out.len() % 4 != 0 {
            out.push(0);
        }
        out.extend_from_slice(data);
        while out.len() % 4 != 0 {
            out.push(0);
        }
    };
    for (i, (name, mode, data)) in files.iter().enumerate() {
        entry(i as u32 + 1, name, *mode, data);
    }
    entry(0, "TRAILER!!!", 0, &[]);
    out
}

fn hex(bytes: &[u8]) -> String {
    use std::fmt::Write as _;
    bytes.iter().fold(String::new(), |mut s, b| {
        let _ = write!(s, "{b:02x}");
        s
    })
}

/// `quench build rpm`: `dist/<name>-<version>-1.x86_64.rpm`, which `rpm -i` and `dnf install` take.
///
/// # Errors
/// As [`linux::build`], or a file that cannot be written.
pub fn rpm(sys: &dyn System, out: &mut dyn Write, project: &Project) -> Result<PathBuf> {
    let f = files(sys, out, project)?;
    let time = build_time();
    let exe_path = format!("/usr/bin/{}", f.name);
    let (exe_name, desktop_name_path) = (format!(".{exe_path}"), format!(".{}", f.desktop_path));
    let payload_files: [(&str, u32, &[u8]); 2] = [
        (&exe_name, 0o100_755, &f.binary),
        (&desktop_name_path, 0o100_644, f.desktop.as_bytes()),
    ];
    let cpio = cpio(&payload_files, time);
    let payload = quench_archive::gzip::compress(&cpio);

    // Where a file lives is a directory (with a slash) and a name, as RPM keeps it.
    let bin_dir = "/usr/bin/";
    let desktop_dir = "/usr/share/applications/";
    let desktop_name = f.desktop_path.rsplit('/').next().unwrap_or_default();
    let digests = [
        hex(&quench_crypto::hash::sha256(&f.binary)),
        hex(&quench_crypto::hash::sha256(f.desktop.as_bytes())),
    ];
    let digests: Vec<&str> = digests.iter().map(String::as_str).collect();
    let total = (f.binary.len() + f.desktop.len()) as u32;

    let mut h = RpmHeader::default();
    h.string(1000, &f.name); // NAME
    h.string(1001, &f.version); // VERSION
    h.string(1002, RELEASE); // RELEASE
    h.string(1004, &f.summary); // SUMMARY
    h.string(1005, &f.summary); // DESCRIPTION
    h.int32(1006, &[time as u32]); // BUILDTIME
    h.string(1007, "localhost"); // BUILDHOST
    h.int32(1009, &[total]); // SIZE
    h.string(1014, "unspecified"); // LICENSE
    h.string(1021, "linux"); // OS
    h.string(1022, "x86_64"); // ARCH
    h.int32(1028, &[f.binary.len() as u32, f.desktop.len() as u32]); // FILESIZES
    h.int16(1030, &[0o100_755, 0o100_644]); // FILEMODES
    h.int16(1033, &[0, 0]); // FILERDEVS
    h.int32(1034, &[time as u32, time as u32]); // FILEMTIMES
    h.strings(1035, &digests); // FILEDIGESTS
    h.strings(1036, &["", ""]); // FILELINKTOS
    h.int32(1037, &[0, 0]); // FILEFLAGS
    h.strings(1039, &["root", "root"]); // FILEUSERNAME
    h.strings(1040, &["root", "root"]); // FILEGROUPNAME
    h.string(1064, "4.18.0"); // RPMVERSION
    h.int32(1095, &[1, 1]); // FILEDEVICES
    h.int32(1096, &[1, 2]); // FILEINODES
    h.strings(1097, &["", ""]); // FILELANGS
    h.int32(1116, &[0, 1]); // DIRINDEXES
    h.strings(1117, &[f.name.as_str(), desktop_name]); // BASENAMES
    h.strings(1118, &[bin_dir, desktop_dir]); // DIRNAMES
    h.string(1124, "cpio"); // PAYLOADFORMAT
    h.string(1125, "gzip"); // PAYLOADCOMPRESSOR
    h.string(1126, "9"); // PAYLOADFLAGS
    h.int32(5011, &[8, 8]); // FILEDIGESTALGO: SHA-256
    h.strings(5092, &[&hex(&quench_crypto::hash::sha256(&payload))]); // PAYLOADDIGEST
    h.int32(5093, &[8]); // PAYLOADDIGESTALGO
    let header = h.encode(63);

    // The signature header vouches for the other two: their size and a SHA-256 of the header.
    let mut s = RpmHeader::default();
    s.int32(1000, &[(header.len() + payload.len()) as u32]); // SIZE
    s.int32(1007, &[cpio.len() as u32]); // PAYLOADSIZE (uncompressed)
    s.string(273, &hex(&quench_crypto::hash::sha256(&header))); // SHA256 of the header
    let mut signature = s.encode(62);
    while signature.len() % 8 != 0 {
        signature.push(0);
    }

    let mut lead = vec![0xed, 0xab, 0xee, 0xdb, 3, 0, 0, 0, 0, 1]; // magic, 3.0, binary, i386
    let label = format!("{}-{}-{RELEASE}", f.name, f.version);
    let mut name = [0u8; 66];
    let take = label.len().min(65);
    name[..take].copy_from_slice(&label.as_bytes()[..take]);
    lead.extend_from_slice(&name);
    lead.extend_from_slice(&[0, 1, 0, 5]); // linux, header-style signature
    lead.extend_from_slice(&[0; 16]);

    let mut archive = lead;
    archive.extend(signature);
    archive.extend(header);
    archive.extend(payload);
    let target = project
        .dist()
        .join(format!("{}-{}-{RELEASE}.x86_64.rpm", f.name, f.version));
    std::fs::write(&target, archive)?;
    writeln!(out, "rpm {}", target.display())?;
    Ok(target)
}

