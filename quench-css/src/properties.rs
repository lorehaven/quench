/// Properties that are accepted and have no effect here: they are about input devices, scrolling behaviour,
/// animation, or a browser's own controls. A native window has its own answers to these.
pub const IGNORED: &[&str] = &[
    "cursor",
    "user-select",
    "will-change",
    "overscroll-behavior",
    "overscroll-behavior-x",
    "overscroll-behavior-y",
    "overflow-anchor",
    "scrollbar-width",
    "scrollbar-color",
    "accent-color",
    "-webkit-tap-highlight-color",
    "-webkit-touch-callout",
    "-webkit-overflow-scrolling",
];

/// Whether `name` is a property this engine knows (supported or ignored on purpose).
#[must_use]
pub fn is_known(name: &str) -> bool {
    name.starts_with("--") || SUPPORTED.contains(&name) || IGNORED.contains(&name)
}
